#!/usr/bin/env python3
"""Trusted Runtime Host request/transaction context provenance.

The REQUEST_ID used for Authority Broker grants is not trusted merely because a
caller passes a string. The trusted Runtime Host mints an immutable request
context from a supervisor-inherited HMAC secret, keeps the context lifecycle in
host memory, and never exposes the HMAC key to the visual/request process.

Security properties:
- bootstrap is one-shot from a supervisor-inherited non-seekable descriptor;
- bootstrap takes ownership of that descriptor and closes it on every path;
- the authority is bound to exactly one Runtime Host PID;
- forked children are permanently invalidated and cannot inherit or re-bootstrap
  the parent Host request-context authority;
- request IDs are generated by the Host, never supplied by a visual caller;
- context fields are authenticated with HMAC-SHA256;
- ACTIVE contexts transition atomically to exactly one terminal state;
- both CONSUMED and CANCELLED identities remain tombstoned for Host-process
  lifetime and can never be issued ACTIVE again;
- terminal contexts remain cryptographically verifiable for durable Runtime
  bindings/audit in the owning Host process, but cannot authorize another
  materialization transaction;
- Python private names are not treated as the trust boundary. The HMAC secret,
  owning PID, at-fork invalidation, and supervisor/process isolation are the
  trust boundary.

The supervisor must pass a dedicated one-shot pipe/socket read capability and
must not retain another process-local readable copy. Seekable bootstrap sources
(files/memfd/temp files) are rejected so the secret cannot be rewound/replayed.
The trusted Host is a no-fork authority process: after ``fork()``, the child copy
of this authority is destroyed and all public authority operations fail closed.
"""
from __future__ import annotations

import errno
import hashlib
import hmac
import json
import os
import secrets
import threading
import time
from dataclasses import dataclass

MIN_CONTEXT_KEY_BYTES = 32
MAX_CONTEXT_KEY_BYTES = 4096


@dataclass(frozen=True)
class RuntimeHostRequestContext:
    request_id: str
    session_id: str
    activation_id: str
    source_revision: str
    issued_at_unix: int
    nonce: str
    authority_id: str
    mac_hex: str


def _required_text(value: object, name: str) -> str:
    if type(value) is not str or not value:
        raise ValueError(f"RUNTIME_HOST_REQUEST_CONTEXT_{name}_REQUIRED")
    return value


def _body(context: RuntimeHostRequestContext) -> dict[str, object]:
    return {
        "REQUEST_ID": context.request_id,
        "SESSION_ID": context.session_id,
        "ACTIVATION_ID": context.activation_id,
        "SOURCE_REVISION": context.source_revision,
        "ISSUED_AT_UNIX": context.issued_at_unix,
        "NONCE": context.nonce,
        "AUTHORITY_ID": context.authority_id,
    }


def _canonical_body(context: RuntimeHostRequestContext) -> bytes:
    return json.dumps(
        _body(context),
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")


def _proof_digest_unchecked(context: RuntimeHostRequestContext) -> str:
    return hashlib.sha256(
        json.dumps(
            {**_body(context), "MAC_HEX": context.mac_hex},
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
    ).hexdigest()


def _validate_owned_bootstrap_fd(fd: int) -> None:
    if type(fd) is not int or fd < 0:
        raise ValueError("RUNTIME_HOST_REQUEST_CONTEXT_BOOTSTRAP_FD_INVALID")
    try:
        os.fstat(fd)
    except OSError as exc:
        raise RuntimeError("RUNTIME_HOST_REQUEST_CONTEXT_BOOTSTRAP_FD_UNAVAILABLE") from exc


def _close_owned_bootstrap_fd(fd: int) -> None:
    _validate_owned_bootstrap_fd(fd)
    try:
        os.close(fd)
    except OSError as exc:
        raise RuntimeError("RUNTIME_HOST_REQUEST_CONTEXT_BOOTSTRAP_FD_CLOSE_FAILED") from exc


def _consume_bootstrap_key_fd(fd: int) -> bytearray:
    """Consume and close the exact one-shot supervisor descriptor."""

    _validate_owned_bootstrap_fd(fd)
    data = bytearray()
    try:
        try:
            os.set_inheritable(fd, False)
        except OSError as exc:
            raise RuntimeError("RUNTIME_HOST_REQUEST_CONTEXT_BOOTSTRAP_FD_UNAVAILABLE") from exc

        try:
            os.lseek(fd, 0, os.SEEK_CUR)
        except OSError as exc:
            if exc.errno != errno.ESPIPE:
                raise RuntimeError(
                    "RUNTIME_HOST_REQUEST_CONTEXT_BOOTSTRAP_FD_SEEK_CHECK_FAILED"
                ) from exc
        else:
            raise PermissionError(
                "RUNTIME_HOST_REQUEST_CONTEXT_BOOTSTRAP_FD_SEEKABLE_FORBIDDEN"
            )

        while True:
            try:
                chunk = os.read(fd, 4096)
            except OSError as exc:
                raise RuntimeError(
                    "RUNTIME_HOST_REQUEST_CONTEXT_BOOTSTRAP_FD_READ_FAILED"
                ) from exc
            if not chunk:
                break
            data.extend(chunk)
            if len(data) > MAX_CONTEXT_KEY_BYTES:
                raise ValueError("RUNTIME_HOST_REQUEST_CONTEXT_BOOTSTRAP_KEY_TOO_LARGE")
    finally:
        try:
            os.close(fd)
        except OSError:
            pass

    if len(data) < MIN_CONTEXT_KEY_BYTES:
        for index in range(len(data)):
            data[index] = 0
        raise ValueError("RUNTIME_HOST_REQUEST_CONTEXT_BOOTSTRAP_KEY_TOO_SHORT")
    return data


_BOOTSTRAP_LOCK = threading.RLock()
_CONTEXT_KEY: bytearray | None = None
_AUTHORITY_ID: str | None = None
_AUTHORITY_PID: int | None = None
_FORK_CHILD_INVALIDATED = False
_ACTIVE_CONTEXTS: dict[str, str] = {}
_CONSUMED_CONTEXTS: dict[str, str] = {}
_CANCELLED_CONTEXTS: dict[str, str] = {}


def _zeroize_context_key_in_this_process() -> None:
    global _CONTEXT_KEY
    key = _CONTEXT_KEY
    if key is not None:
        for index in range(len(key)):
            key[index] = 0
    _CONTEXT_KEY = None


def _invalidate_authority_after_fork_in_child() -> None:
    """Destroy the cloned Host authority in a forked child.

    This callback deliberately does not acquire the inherited lock: another
    parent thread may have owned it at fork time. The child receives fresh
    lifecycle containers and a fresh lock, but remains permanently forbidden
    from acting as a Runtime Host authority process.
    """

    global _BOOTSTRAP_LOCK
    global _AUTHORITY_ID, _AUTHORITY_PID, _FORK_CHILD_INVALIDATED
    global _ACTIVE_CONTEXTS, _CONSUMED_CONTEXTS, _CANCELLED_CONTEXTS

    _zeroize_context_key_in_this_process()
    _AUTHORITY_ID = None
    _AUTHORITY_PID = None
    _ACTIVE_CONTEXTS = {}
    _CONSUMED_CONTEXTS = {}
    _CANCELLED_CONTEXTS = {}
    _BOOTSTRAP_LOCK = threading.RLock()
    _FORK_CHILD_INVALIDATED = True


if hasattr(os, "register_at_fork"):
    os.register_at_fork(after_in_child=_invalidate_authority_after_fork_in_child)


def _assert_runtime_host_authority_process() -> None:
    current_pid = os.getpid()
    if _FORK_CHILD_INVALIDATED:
        raise PermissionError("RUNTIME_HOST_REQUEST_CONTEXT_FORKED_CHILD_FORBIDDEN")
    owner_pid = _AUTHORITY_PID
    if owner_pid is not None and owner_pid != current_pid:
        raise PermissionError("RUNTIME_HOST_REQUEST_CONTEXT_PROCESS_MISMATCH")
    if _CONTEXT_KEY is None or not _AUTHORITY_ID or owner_pid is None:
        raise RuntimeError("RUNTIME_HOST_REQUEST_CONTEXT_AUTHORITY_NOT_BOOTSTRAPPED")


def bootstrap_runtime_host_request_context_authority_from_inherited_fd(fd: int) -> str:
    """Install the Host request-context authority exactly once in one PID.

    The supervisor must invoke this before accepting untrusted request IPC.
    Ownership of ``fd`` transfers to this call. For a valid descriptor, the call
    closes the original FD on success and every failure path, including a
    rejected second bootstrap. A process created by ``fork()`` from a Host that
    imported this module is permanently forbidden from bootstrapping or using
    this authority. There is deliberately no reset/replacement API.
    """

    global _CONTEXT_KEY, _AUTHORITY_ID, _AUTHORITY_PID
    _validate_owned_bootstrap_fd(fd)
    with _BOOTSTRAP_LOCK:
        if _FORK_CHILD_INVALIDATED:
            _close_owned_bootstrap_fd(fd)
            raise PermissionError("RUNTIME_HOST_REQUEST_CONTEXT_FORKED_CHILD_FORBIDDEN")
        if _CONTEXT_KEY is not None or _AUTHORITY_PID is not None:
            _close_owned_bootstrap_fd(fd)
            raise RuntimeError("RUNTIME_HOST_REQUEST_CONTEXT_AUTHORITY_ALREADY_BOOTSTRAPPED")
        key = _consume_bootstrap_key_fd(fd)
        _CONTEXT_KEY = key
        _AUTHORITY_PID = os.getpid()
        _AUTHORITY_ID = "RHCTX-" + hashlib.sha256(key).hexdigest()[:24]
        return _AUTHORITY_ID


def runtime_host_request_context_authority_id() -> str:
    _assert_runtime_host_authority_process()
    authority_id = _AUTHORITY_ID
    if not authority_id:  # defensive; asserted above
        raise RuntimeError("RUNTIME_HOST_REQUEST_CONTEXT_AUTHORITY_NOT_BOOTSTRAPPED")
    return authority_id


def _mac_for(context: RuntimeHostRequestContext) -> str:
    _assert_runtime_host_authority_process()
    key = _CONTEXT_KEY
    if key is None:  # defensive; asserted above
        raise RuntimeError("RUNTIME_HOST_REQUEST_CONTEXT_AUTHORITY_NOT_BOOTSTRAPPED")
    return hmac.new(key, _canonical_body(context), hashlib.sha256).hexdigest()


def runtime_host_request_context_proof_digest(context: RuntimeHostRequestContext) -> str:
    verified = verify_runtime_host_request_context(context, require_active=False)
    return _proof_digest_unchecked(verified)


def issue_runtime_host_request_context(
    session_id: str,
    activation_id: str,
    source_revision: str,
    *,
    now_unix: int | None = None,
) -> RuntimeHostRequestContext:
    """Mint a Host-owned request transaction identity in the owning Host PID."""

    session = _required_text(session_id, "SESSION_ID")
    activation = _required_text(activation_id, "ACTIVATION_ID")
    revision = _required_text(source_revision, "SOURCE_REVISION")
    authority_id = runtime_host_request_context_authority_id()
    issued = int(time.time()) if now_unix is None else int(now_unix)
    if issued < 0:
        raise ValueError("RUNTIME_HOST_REQUEST_CONTEXT_ISSUED_AT_INVALID")

    unsigned = RuntimeHostRequestContext(
        request_id="REQ-" + secrets.token_hex(24),
        session_id=session,
        activation_id=activation,
        source_revision=revision,
        issued_at_unix=issued,
        nonce="RHNONCE-" + secrets.token_hex(24),
        authority_id=authority_id,
        mac_hex="",
    )
    context = RuntimeHostRequestContext(**{**unsigned.__dict__, "mac_hex": _mac_for(unsigned)})
    proof = _proof_digest_unchecked(context)
    with _BOOTSTRAP_LOCK:
        _assert_runtime_host_authority_process()
        if (
            context.request_id in _ACTIVE_CONTEXTS
            or context.request_id in _CONSUMED_CONTEXTS
            or context.request_id in _CANCELLED_CONTEXTS
        ):
            raise RuntimeError("RUNTIME_HOST_REQUEST_CONTEXT_ID_COLLISION")
        _ACTIVE_CONTEXTS[context.request_id] = proof
    return context


def verify_runtime_host_request_context(
    context: RuntimeHostRequestContext,
    *,
    expected_request_id: str | None = None,
    expected_session_id: str | None = None,
    expected_activation_id: str | None = None,
    expected_source_revision: str | None = None,
    require_active: bool = False,
) -> RuntimeHostRequestContext:
    _assert_runtime_host_authority_process()
    if not isinstance(context, RuntimeHostRequestContext):
        raise TypeError("RUNTIME_HOST_REQUEST_CONTEXT_REQUIRED")
    _required_text(context.request_id, "REQUEST_ID")
    _required_text(context.session_id, "SESSION_ID")
    _required_text(context.activation_id, "ACTIVATION_ID")
    _required_text(context.source_revision, "SOURCE_REVISION")
    _required_text(context.nonce, "NONCE")
    _required_text(context.authority_id, "AUTHORITY_ID")
    _required_text(context.mac_hex, "MAC")
    if type(context.issued_at_unix) is not int or context.issued_at_unix < 0:
        raise ValueError("RUNTIME_HOST_REQUEST_CONTEXT_ISSUED_AT_INVALID")
    if context.authority_id != runtime_host_request_context_authority_id():
        raise PermissionError("RUNTIME_HOST_REQUEST_CONTEXT_AUTHORITY_MISMATCH")
    if not hmac.compare_digest(context.mac_hex, _mac_for(context)):
        raise PermissionError("RUNTIME_HOST_REQUEST_CONTEXT_MAC_INVALID")

    checks = {
        "REQUEST_ID": (context.request_id, expected_request_id),
        "SESSION_ID": (context.session_id, expected_session_id),
        "ACTIVATION_ID": (context.activation_id, expected_activation_id),
        "SOURCE_REVISION": (context.source_revision, expected_source_revision),
    }
    for name, (actual, expected) in checks.items():
        if expected is not None and actual != expected:
            raise PermissionError(f"RUNTIME_HOST_REQUEST_CONTEXT_{name}_MISMATCH")

    proof = _proof_digest_unchecked(context)
    if require_active:
        with _BOOTSTRAP_LOCK:
            _assert_runtime_host_authority_process()
            registered = _ACTIVE_CONTEXTS.get(context.request_id)
            if registered is None:
                raise PermissionError("RUNTIME_HOST_REQUEST_CONTEXT_NOT_ACTIVE")
            if not hmac.compare_digest(registered, proof):
                raise PermissionError("RUNTIME_HOST_REQUEST_CONTEXT_ACTIVE_PROOF_MISMATCH")
    return context


def _transition_active_context(
    context: RuntimeHostRequestContext,
    *,
    terminal_state: str,
) -> None:
    """Atomically move an authenticated ACTIVE proof into one terminal registry."""

    verified = verify_runtime_host_request_context(context, require_active=False)
    proof = _proof_digest_unchecked(verified)
    if terminal_state == "CONSUMED":
        terminal = _CONSUMED_CONTEXTS
    elif terminal_state == "CANCELLED":
        terminal = _CANCELLED_CONTEXTS
    else:
        raise ValueError("RUNTIME_HOST_REQUEST_CONTEXT_TERMINAL_STATE_INVALID")

    with _BOOTSTRAP_LOCK:
        _assert_runtime_host_authority_process()
        registered = _ACTIVE_CONTEXTS.get(verified.request_id)
        if registered is None:
            raise PermissionError("RUNTIME_HOST_REQUEST_CONTEXT_NOT_ACTIVE")
        if not hmac.compare_digest(registered, proof):
            raise PermissionError("RUNTIME_HOST_REQUEST_CONTEXT_ACTIVE_PROOF_MISMATCH")
        if (
            verified.request_id in _CONSUMED_CONTEXTS
            or verified.request_id in _CANCELLED_CONTEXTS
        ):
            raise RuntimeError("RUNTIME_HOST_REQUEST_CONTEXT_LIFECYCLE_STATE_CORRUPT")

        terminal[verified.request_id] = proof
        try:
            del _ACTIVE_CONTEXTS[verified.request_id]
        except BaseException:
            terminal.pop(verified.request_id, None)
            raise


def consume_runtime_host_request_context(context: RuntimeHostRequestContext) -> None:
    """Atomically consume one ACTIVE Host transaction after successful binding."""

    _transition_active_context(context, terminal_state="CONSUMED")


def cancel_runtime_host_request_context(context: RuntimeHostRequestContext) -> None:
    """Atomically revoke one ACTIVE transaction and retain a terminal tombstone."""

    _transition_active_context(context, terminal_state="CANCELLED")


